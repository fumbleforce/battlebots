def clone_part(original,name,at,direction=None,outward=None):
    duplicate=original.copy();duplicate.name=name;bpy.context.collection.objects.link(duplicate)
    duplicate.parent=None;duplicate.location=gv(at);duplicate.hide_render=False
    if direction is not None:
        d=Vector(direction).normalized();right=Vector((0,1,0)).cross(outward).normalized();forward=right.cross(d)
        # Columns correspond to the Godot basis transformed to Blender.
        conv=Matrix(((1,0,0),(0,0,-1),(0,1,0)))
        rot=Matrix((right,d,forward)).transposed()
        duplicate.rotation_mode='QUATERNION';duplicate.rotation_quaternion=(conv@rot@conv.inverted()).to_quaternion()
    elif outward is not None:
        conv=Matrix(((1,0,0),(0,0,-1),(0,1,0)))
        right=Vector(outward).cross(Vector((0,1,0))).normalized()
        rot=Matrix((right,Vector((0,1,0)),-Vector(outward))).transposed()
        duplicate.rotation_mode='QUATERNION';duplicate.rotation_quaternion=(conv@rot@conv.inverted()).to_quaternion()
    for child in original.children:
        c=child.copy();c.data=child.data;c.parent=duplicate;c.hide_render=False;bpy.context.collection.objects.link(c)
    return duplicate

