def finalize(group):
    items=groups[group]
    if not items:return
    bpy.ops.object.select_all(action='DESELECT')
    for obj in items:
        obj.select_set(True);bpy.context.view_layer.objects.active=obj
        for mod in list(obj.modifiers):bpy.ops.object.modifier_apply(modifier=mod.name)
        obj.select_set(False)
    for obj in items:obj.select_set(True)
    bpy.context.view_layer.objects.active=items[0]
    bpy.ops.object.join();obj=bpy.context.object
    world=obj.matrix_world.copy()
    obj.data.transform(group.matrix_world.inverted()@world)
    obj.parent=group;obj.matrix_parent_inverse=Matrix.Identity(4);obj.matrix_basis=Matrix.Identity(4)
    obj.name=group.name+'Surface'
    # Every polygon has intentional weighted normals; preserve them in glTF.
    bpy.ops.object.select_all(action='DESELECT')

