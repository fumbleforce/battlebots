def export(obj,filename):
    bpy.ops.object.select_all(action='DESELECT')
    for item in descendants(obj):item.select_set(True)
    bpy.context.view_layer.objects.active=obj
    bpy.ops.export_scene.gltf(filepath=str(RUNTIME/filename),export_format='GLB',use_selection=True,
        export_yup=True,export_apply=True,export_texcoords=True,export_normals=True,
        export_materials='EXPORT',export_cameras=False,export_lights=False,
        export_animations=False,export_extras=True)
    bpy.ops.object.select_all(action='DESELECT')
    # glTF permits external image URIs inside a GLB. Share the material maps
    # between all four meshes rather than asking Godot to extract four copies.
    path=RUNTIME/filename
    raw=path.read_bytes();json_len=struct.unpack_from('<I',raw,12)[0]
    document=json.loads(raw[20:20+json_len])
    binary_start=20+json_len+8
    binary=raw[binary_start:]
    image_views={im['bufferView'] for im in document.get('images',[]) if 'bufferView' in im}
    for im in document.get('images',[]):
        im.pop('bufferView',None);im.pop('mimeType',None)
        im['uri']=im['name']+'.png'
        if not (RUNTIME/im['uri']).exists():raise RuntimeError('Missing shared texture '+im['uri'])
    remap={};views=[];packed=bytearray()
    for i,view in enumerate(document['bufferViews']):
        if i in image_views:continue
        while len(packed)%4:packed.append(0)
        old_offset=view.get('byteOffset',0);chunk=binary[old_offset:old_offset+view['byteLength']]
        new_view=dict(view);new_view['byteOffset']=len(packed);remap[i]=len(views);views.append(new_view);packed.extend(chunk)
    for accessor in document.get('accessors',[]):
        if 'bufferView' in accessor:accessor['bufferView']=remap[accessor['bufferView']]
    document['bufferViews']=views;document['buffers'][0]['byteLength']=len(packed)
    while len(packed)%4:packed.append(0)
    jb=json.dumps(document,separators=(',',':')).encode('utf8')
    while len(jb)%4:jb+=b' '
    path.write_bytes(struct.pack('<4sII',b'glTF',2,12+8+len(jb)+8+len(packed))
        +struct.pack('<I4s',len(jb),b'JSON')+jb+struct.pack('<I4s',len(packed),b'BIN\0')+packed)

