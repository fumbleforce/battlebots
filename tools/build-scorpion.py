def gv(p): return Vector((p[0], -p[2], p[1]))
def godot(p): return [round(p.x, 6), round(p.z, 6), round(-p.y, 6)]
def linear(c): return c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4
def srgb(rgb): return tuple(linear(v) for v in rgb)

N = 1024
Y, X = np.mgrid[0:N, 0:N].astype(np.float32)
u, v = X / (N-1), Y / (N-1)
rng = np.random.default_rng(571)
grain = rng.random((N,N), dtype=np.float32)
noise = grain.copy()
for scale in (2, 4, 9, 19):
    noise += (np.sin(u * scale * 7 + .7) * np.cos(v * scale * 8 + .23) + 1) * .12
edge = np.minimum.reduce([u, v, 1-u, 1-v])
wear_noise=(np.sin(u*87+np.sin(v*47))*np.cos(v*61+np.cos(u*39))+1)*.5
chip = (edge < (.0015 + wear_noise*.007)) & (wear_noise>.60)
# Nonuniform islands of exposed substrate and directional abrasion.
for _ in range(74):
    cx, cy = rng.uniform(0,1,2)
    rx, ry = rng.uniform(.003,.026), rng.uniform(.002,.020)
    blot = ((u-cx)/rx)**2 + ((v-cy)/ry)**2
    angle=np.arctan2((v-cy)/ry,(u-cx)/rx)
    broken_edge=.57+.19*np.sin(angle*7+cx*19)+.12*np.cos(angle*13+cy*27)
    chip |= (blot < broken_edge*(.67+wear_noise*.43))
scratches = np.zeros((N,N), dtype=bool)
for _ in range(20):
    cx,cy=rng.uniform(.02,.98,2)
    length=rng.uniform(.005,.052)
    scratches |= (abs((v-cy) - (u-cx)*.32)<rng.uniform(.0003,.0012)) & (abs(u-cx)<length)
chip |= scratches

def save_image(name, data, noncolor=False):
    image=bpy.data.images.new(name,width=N,height=N,alpha=True)
    image.colorspace_settings.name='Non-Color' if noncolor else 'sRGB'
    rgba=np.ones((N,N,4),dtype=np.float32)
    rgba[:,:,:3]=np.clip(data,0,1)
    image.pixels.foreach_set(rgba.reshape(-1))
    image.filepath_raw=str(RUNTIME/(name+'.png'))
    image.file_format='PNG'
    image.save()
    # Generated byte buffers and file textures can be sampled differently.
    # Reload the saved 8-bit sRGB/Non-Color PNG so Blender and Godot see exactly
    # the same portable texture bytes. Artist colors are encoded sRGB inputs.
    image.source='FILE'
    image.reload()
    image.colorspace_settings.name='Non-Color' if noncolor else 'sRGB'
    return image

def make_maps(name, base, metal, rough, painted=True, stripe=False):
    color=np.ones((N,N,3),dtype=np.float32)*np.array(base,dtype=np.float32)
    color *= (.965 + grain[:,:,None]*.045 + (noise[:,:,None]-.8)*.025)
    if stripe:
        # Correct aspect for the hammer's narrow, tall insert: broad 45 degree
        # bands in world space instead of stretched pinstripes.
        bands=((u*.60+v*2.20)%1)<.44
        color[bands]*=.105
    marks=chip if painted else (scratches & (grain>.35))
    color[marks]=np.array((.25,.245,.225))*(.8+grain[marks,None]*.45)
    # Rust catches only deep paint chips; exposed edges stay bright steel.
    rust=marks & (grain<.07) & (edge>.023)
    color[rust]=(.19,.083,.027)
    mr=np.ones((N,N,3),dtype=np.float32)
    mr[:,:,1]=rough+(grain-.5)*.07
    mr[:,:,2]=metal
    mr[marks,1]=.32+(grain[marks]-.5)*.1
    mr[marks,2]=.96
    height=(grain-.5)*.035
    height[marks]-=.1
    dx=(np.roll(height,1,1)-np.roll(height,-1,1))*.25
    dy=(np.roll(height,1,0)-np.roll(height,-1,0))*.25
    normal=np.stack([.5+dx,.5+dy,np.ones_like(grain)],2)
    return save_image(name+'_base',color),save_image(name+'_orm',mr,True),save_image(name+'_normal',normal,True)

def textured(name, color, metal, rough, painted=True, stripe=False):
    a,m,n=make_maps(name,color,metal,rough,painted,stripe)
    mat=bpy.data.materials.new(name)
    mat.use_nodes=True
    nodes=mat.node_tree.nodes; links=mat.node_tree.links
    bs=nodes.get('Principled BSDF')
    bs.inputs['Metallic'].default_value=metal
    bs.inputs['Roughness'].default_value=rough
    for image,kind in [(a,'albedo'),(m,'orm'),(n,'normal')]:
        node=nodes.new('ShaderNodeTexImage'); node.image=image
        if kind=='albedo': links.new(node.outputs['Color'],bs.inputs['Base Color'])
        if kind=='orm':
            split=nodes.new('ShaderNodeSeparateColor')
            links.new(node.outputs['Color'],split.inputs['Color'])
            links.new(split.outputs['Green'],bs.inputs['Roughness'])
            links.new(split.outputs['Blue'],bs.inputs['Metallic'])
        if kind=='normal':
            nm=nodes.new('ShaderNodeNormalMap'); nm.inputs['Strength'].default_value=.3
            links.new(node.outputs['Color'],nm.inputs['Color'])
            links.new(nm.outputs['Normal'],bs.inputs['Normal'])
    mat.diffuse_color=(*srgb(color),1)
    return mat

def simple(name,color,metal,rough,emission=0):
    mat=bpy.data.materials.new(name);mat.use_nodes=True
    bs=mat.node_tree.nodes.get('Principled BSDF')
    bs.inputs['Base Color'].default_value=(*srgb(color),1)
    bs.inputs['Metallic'].default_value=metal
    bs.inputs['Roughness'].default_value=rough
    if emission:
        bs.inputs['Emission Color'].default_value=(*srgb(color),1)
        bs.inputs['Emission Strength'].default_value=emission
    mat.diffuse_color=(*srgb(color),1)
    return mat

