def ring_shell(name,rings,mat,group,bevel=.018):
    verts=[(x*scale,y,z*scale) for y,scale in rings for x,z in profile]
    n=len(profile);faces=[tuple(reversed(range(n))),tuple(range((len(rings)-1)*n,len(rings)*n))]
